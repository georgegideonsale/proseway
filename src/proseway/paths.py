"""Where Proseway keeps its data on each operating system."""

from __future__ import annotations

import os
import sys
from pathlib import Path


def default_data_dir() -> Path:
    override = os.environ.get("PROSEWAY_DATA_DIR")
    if override:
        return Path(override).expanduser().resolve()
    if sys.platform == "win32":
        base = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
        return Path(base) / "Proseway"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "Proseway"
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "proseway"


class DataPaths:
    """All on-disk locations, derived from one root directory."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.db = self.root / "proseway.sqlite3"
        self.books = self.root / "books"
        self.tmp = self.root / "tmp"

    def ensure(self) -> DataPaths:
        for p in (self.root, self.books, self.tmp):
            p.mkdir(parents=True, exist_ok=True)
        return self

    def book_dir(self, book_id: str) -> Path:
        # book ids are generated by us (uuid4 hex); still guard against traversal.
        if not book_id.isalnum():
            raise ValueError("invalid book id")
        return self.books / book_id

    def original_pdf(self, book_id: str) -> Path:
        return self.book_dir(book_id) / "original.pdf"

    def pages_dir(self, book_id: str) -> Path:
        return self.book_dir(book_id) / "pages"

    def assets_dir(self, book_id: str) -> Path:
        return self.book_dir(book_id) / "assets"
